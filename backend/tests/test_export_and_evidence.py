def _csv(c, **params):
    r = c.get("/api/merchants/M001/export/csv", params=params)
    assert r.status_code == 200 and r.headers["content-type"].startswith("text/csv")
    lines = r.text.splitlines()
    comments = [l for l in lines if l.startswith("#")]
    rows = list(csv.DictReader(io.StringIO("\n".join(l for l in lines if not l.startswith("#")))))
    return r, comments, rows


def _sum(rows, entry_type):
    return sum(round(float(r["amount_rupees"]) * 100) for r in rows if r["entry_type"] == entry_type)


def test_csv_demo_day(real):
    run_m001_demo(real)
    r, comments, rows = _csv(real, start_date="2026-11-15", end_date="2026-11-15")
    assert 'filename="naanayam_M001_2026-11-15_2026-11-15.csv"' in r.headers["content-disposition"]
    assert [c.split(":")[0] for c in comments[:4]] == ["# merchant", "# period", "# generated as_of", "# ledger verify"]
    assert "VALID" in comments[3] and comments[4].startswith("# UPI payments only") and "original payment" in comments[5]
    assert list(rows[0].keys()) == CSV_COLUMNS and len(rows) == 17  # expense + 15 payments + 1 reclassification
    lakshmi = [x for x in rows if x["source_id"].endswith("-015")]
    assert [x["amount_rupees"] for x in lakshmi] == ["2000.00", "2000.00"]
    assert lakshmi[-1]["classification"] == "FAMILY" and lakshmi[0]["payer_or_description"] == "Lakshmi R"
    expense = next(x for x in rows if x["entry_type"] == "EXPENSE")
    assert expense["payer_or_description"] == "Kaaikari, Koyambedu" and expense["expense_category"] == "STOCK_PURCHASE"


def test_csv_reconciles_with_summary_over_history(real):
    period = {"start_date": "2026-08-01", "end_date": "2026-10-31"}
    _, _, rows = _csv(real, **period)
    s = real.get("/api/merchants/M001/summary", params=period).json()
    assert _sum(rows, "PAYMENT_IN") == s["total_collections"]["amount_paise"]
    assert _sum(rows, "REFUND_OUT") == s["refunds"]["amount_paise"] > 0
    assert _sum(rows, "REVERSAL") == s["reversals"]["amount_paise"]
    assert _sum(rows, "EXPENSE") - _sum(rows, "EXPENSE_VOID") == s["expenses"]["amount_paise"]
    assert [int(x["seq"]) for x in rows] == sorted(int(x["seq"]) for x in rows)


