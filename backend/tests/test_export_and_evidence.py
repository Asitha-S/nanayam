def test_evidence_difference_and_missing_amount(real):
    nid = _notice({"amount_questioned_paise": {"value": 90000000, "origin": "EXTRACTED_FROM_NOTICE", "confidence": 0.95}})
    ev = real.get(f"/api/merchants/M001/notices/{nid}/evidence").json()
    assert ev["difference_vs_notice"]["amount_paise"] == 90000000 - 84216200
    assert "differs from ledger collections by ₹57,838" in ev["difference_vs_notice"]["explanation"]
    nid2 = _notice({"amount_questioned_paise": {"value": None, "origin": "NOT_FOUND", "confidence": None}})
    ev2 = real.get(f"/api/merchants/M001/notices/{nid2}/evidence").json()
    assert ev2["amount_questioned"]["origin"] == "NOT_FOUND" and ev2["difference_vs_notice"]["amount_paise"] is None
    assert "Amount questioned was not found on the notice." in ev2["ca_review_warnings"]


def test_evidence_warns_on_tamper_and_unknown_notice(real):
    nid = _notice()
    entry = real.get("/api/merchants/M001/ledger", params={"start_date": "2026-09-01", "end_date": "2026-09-01",
                                                          "limit": 1}).json()["items"][0]["ledger_entry_id"]
