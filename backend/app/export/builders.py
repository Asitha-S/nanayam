"""CA export (contract section 11): csv_export and pdf_export. Owner: Asitha.

Rows follow the attribution of /summary (DATA_AND_LOGIC 7.3): a payment dated in the period brings all its ledger
entries (PAYMENT_IN, RECLASSIFICATION, REFUND_OUT, REVERSAL, whatever their own date), and an expense dated in the
period brings EXPENSE and EXPENSE_VOID. So the file reconciles with /summary for the same period.
Amounts come from finance.summary.compute and the ledger; money text from money.display.
"""
from __future__ import annotations

import csv
import io
import sqlite3
from datetime import date

from .. import clock, money, repo
from ..finance.summary import ATTRIBUTION_NOTE, SCOPE_NOTE, compute
from ..ledger import writer as ledger
from ..ledger.hashing import confidence_from_db
from ..notice.evidence import FIXED_WARNINGS
from ..services.insights import GST, verify_status
from .pdf import SimplePdf

CSV_COLUMNS = [
    "ledger_entry_id", "seq", "entry_type", "effective_at", "source_type", "source_id", "payer_or_description",
    "amount_rupees", "classification", "classification_source", "confidence", "expense_category",
    "supersedes_entry_id", "hash",
]
FOOTER = "Generated by Naanayam from synthetic demo data"
MAX_UNRESOLVED_LINES = 30

ENTRIES_SQL = """
WITH pays AS (SELECT transaction_id FROM payments WHERE merchant_id = :m AND substr(timestamp, 1, 10) BETWEEN :s AND :e),
     exps AS (SELECT expense_id FROM expenses WHERE merchant_id = :m AND substr(timestamp, 1, 10) BETWEEN :s AND :e)
SELECT le.*,
  CASE WHEN le.source_type IN ('PAYMENT', 'REVERSAL') THEN
         (SELECT py.payer_name FROM payments p JOIN payers py ON py.payer_id = p.payer_id WHERE p.transaction_id = le.source_id)
       WHEN le.source_type = 'REFUND' THEN
         (SELECT py.payer_name FROM refunds r JOIN payments p ON p.transaction_id = r.transaction_id
          JOIN payers py ON py.payer_id = p.payer_id WHERE r.refund_id = le.source_id)
       ELSE (SELECT description FROM expenses x WHERE x.expense_id = le.source_id) END AS who
FROM ledger_entries le
WHERE le.merchant_id = :m AND (
      (le.source_type IN ('PAYMENT', 'REVERSAL') AND le.source_id IN pays)
   OR (le.source_type = 'REFUND' AND le.source_id IN (SELECT refund_id FROM refunds WHERE transaction_id IN pays))
   OR (le.source_type = 'EXPENSE' AND le.source_id IN exps))
ORDER BY le.seq
"""

UNRESOLVED_SQL = """
SELECT p.transaction_id, p.timestamp, py.payer_name, p.amount_paise FROM payments p
JOIN payers py ON py.payer_id = p.payer_id
JOIN ledger_entries le ON le.ledger_entry_id = (
    SELECT l2.ledger_entry_id FROM ledger_entries l2 WHERE l2.source_type = 'PAYMENT' AND l2.source_id = p.transaction_id
      AND l2.entry_type IN ('PAYMENT_IN', 'RECLASSIFICATION') ORDER BY l2.seq DESC LIMIT 1)
WHERE p.merchant_id = ? AND substr(p.timestamp, 1, 10) BETWEEN ? AND ? AND le.classification = 'PENDING'
  AND NOT EXISTS (SELECT 1 FROM reversals v WHERE v.transaction_id = p.transaction_id)
ORDER BY p.timestamp
"""


def rupees(paise: int) -> str:
    """The only place rupees appear as a decimal (contract 11)."""
    return f"{paise // 100}.{paise % 100:02d}"


def _header(conn: sqlite3.Connection, merchant_id: str) -> tuple[sqlite3.Row, str, str]:
    m = repo.require_merchant(conn, merchant_id)
    as_of = clock.iso(clock.effective_now(ledger.last_created_at(conn, merchant_id)))
    return m, as_of, verify_status(conn, merchant_id)


def filename(merchant_id: str, start: date, end: date, ext: str) -> str:
    return f"naanayam_{merchant_id}_{start.isoformat()}_{end.isoformat()}.{ext}"


def csv_export(conn: sqlite3.Connection, *, merchant_id: str, start: date, end: date) -> bytes:
    m, as_of, status = _header(conn, merchant_id)
    buf = io.StringIO()
    for line in (f"merchant: {merchant_id} ({m['display_name']})", f"period: {start} to {end}", f"generated as_of: {as_of}",
                 f"ledger verify: {status}", SCOPE_NOTE, ATTRIBUTION_NOTE):
        buf.write(f"# {line}\n")
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(CSV_COLUMNS)
    rows = conn.execute(ENTRIES_SQL, {"m": merchant_id, "s": start.isoformat(), "e": end.isoformat()}).fetchall()
    for r in rows:
        conf = confidence_from_db(r["confidence"])
        w.writerow([r["ledger_entry_id"], r["seq"], r["entry_type"], r["effective_at"], r["source_type"], r["source_id"],
                    r["who"] or "", rupees(r["amount_paise"]), r["classification"] or "", r["classification_source"] or "",
                    "" if conf is None else conf, r["expense_category"] or "", r["supersedes_entry_id"] or "", r["hash"]])
    return buf.getvalue().encode("utf-8")


def pdf_export(conn: sqlite3.Connection, *, merchant_id: str, start: date, end: date) -> bytes:
    m, as_of, status = _header(conn, merchant_id)
    b = compute(conn, merchant_id, start, end)
    treatment, basis = GST[m["business_category"]]
    pdf = SimplePdf(footer=FOOTER)
    pdf.line(f"Naanayam CA pack: {m['display_name']} ({merchant_id})", bold=True, size=15)
    pdf.line(f"Period {start} to {end}    Generated {as_of}    Ledger verify: {status}")
    pdf.gap()
    pdf.line("Summary", bold=True, size=12)
    for label, paise in [("Total UPI collections", b.total_collections), ("Business sales", b.business_sales),
                         ("Family transfers", b.family_transfers), ("Refunds and reversals", b.refunds + b.reversals),
                         (f"Pending ({b.pending_count} payments)", b.pending), ("Expenses recorded", b.expenses),
                         ("Recorded profit", b.profit)]:
        pdf.row(label, money.display(paise))
    pdf.gap()
    pdf.wrapped(SCOPE_NOTE)
    pdf.wrapped(ATTRIBUTION_NOTE)
    pdf.gap()
    pdf.line("GST treatment (declared category)", bold=True, size=12)
    pdf.line(f"{m['business_category']}: {treatment}")
    pdf.wrapped(basis)
    pdf.gap()
    pending = conn.execute(UNRESOLVED_SQL, (merchant_id, start.isoformat(), end.isoformat())).fetchall()
    pdf.line(f"Unresolved items ({len(pending)})", bold=True, size=12)
    for r in pending[:MAX_UNRESOLVED_LINES]:
        pdf.line(f"{r[1][:10]}  {r[2]}  {money.display(r[3])}  {r[0]}")
    if len(pending) > MAX_UNRESOLVED_LINES:
        pdf.line(f"... and {len(pending) - MAX_UNRESOLVED_LINES} more (see the CSV)")
    if not pending:
        pdf.line("None.")
    pdf.gap()
    pdf.line("CA review warnings", bold=True, size=12)
    warnings = list(FIXED_WARNINGS)
    if b.pending_count:
        warnings.append(f"{b.pending_count} payments in this period are still unconfirmed.")
    if status != "VALID":
        warnings.append("Ledger integrity check failed.")
    warnings.append("Naanayam organises records. It does not give tax or legal advice. A CA must review.")
    for w in warnings:
        pdf.wrapped(f"- {w}")
    return pdf.render()
