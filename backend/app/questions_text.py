"""Question text for a payment (VOICE_AND_NOTICE section 7, key `question_payment`).

Reads backend/app/voice/templates/{lang}.json when Charulatha / Nagasai Sree have added it;
until then uses the drafts from the spec. Never generated by an LLM.
"""
from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path

from . import money

TEMPLATES_DIR = Path(__file__).resolve().parent / "voice" / "templates"

DRAFT_QUESTION = {
    "ta": "{payer_name} கிட்ட இருந்து {amount} வந்திருக்கு. இது கடை வியாபாரமா, வீட்டு பணமா?",
    "te": "{payer_name} నుండి {amount} వచ్చింది. ఇది షాప్ అమ్మకమా, ఇంటి డబ్బా?",
    "en": "{amount} received from {payer_name}. Is this a shop sale or family money?",
}
RUPEE_WORD = {"ta": "ரூபாய்", "te": "రూపాయలు"}


@lru_cache
def _template(lang: str) -> str:
    path = TEMPLATES_DIR / f"{lang}.json"
    if path.exists():
        text = json.loads(path.read_text(encoding="utf-8")).get("question_payment")
        if text:
            return text
    return DRAFT_QUESTION[lang]


def spoken_amount(paise: int, lang: str) -> str:
    """'2,000 ரூபாய்' for ta/te; '₹2,000' for en."""
    shown = money.display(paise)
    if lang in RUPEE_WORD:
        return f"{shown.replace(money.RUPEE, '')} {RUPEE_WORD[lang]}"
    return shown


def question_text(payer_name: str, amount_paise: int, lang: str) -> str:
    return _template(lang).format(payer_name=payer_name, amount=spoken_amount(amount_paise, lang))


def question_text_en(payer_name: str, amount_paise: int) -> str:
    return DRAFT_QUESTION["en"].format(payer_name=payer_name, amount=money.display(amount_paise))
